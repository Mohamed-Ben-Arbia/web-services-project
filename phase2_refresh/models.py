from datetime import datetime
from errors import APIError


def require_str(data, field, required=True):
    value = data.get(field)
    if value is None:
        if required:
            raise APIError(f"Field '{field}' is required")
        return ""
    if not isinstance(value, str):
        raise APIError(f"Field '{field}' must be a string")
    if required and not value.strip():
        raise APIError(f"Field '{field}' cannot be empty")
    return value.strip()


def require_int(data, field):
    value = data.get(field)
    if value is None:
        raise APIError(f"Field '{field}' is required")
    # In Python, True and False count as integers, so we reject them explicitly
    if isinstance(value, bool) or not isinstance(value, int):
        raise APIError(f"Field '{field}' must be an integer")
    return value


class Report:
    def __init__(self, id_r, title, type_, k1, k2, k3, release_date):
        self.ID_R = id_r
        self.Title = title
        self.Type = type_
        self.K1 = k1
        self.K2 = k2
        self.K3 = k3
        self.Release_Date = release_date

    @staticmethod
    def from_json(data, id_r):
        # The server generates the ID, the client must not send it
        if "ID_R" in data or "id" in data:
            raise APIError("Do not send an id, it is generated by the server")

        title = require_str(data, "Title")
        type_ = require_str(data, "Type")
        k1 = require_str(data, "K1")
        k2 = require_str(data, "K2", required=False)
        k3 = require_str(data, "K3", required=False)
        date = require_str(data, "Release_Date")

        try:
            datetime.strptime(date, "%Y-%m-%d")
        except ValueError:
            raise APIError("Release_Date must be a valid date in YYYY-MM-DD format")

        return Report(id_r, title, type_, k1, k2, k3, date)

    def to_dict(self):
        return self.__dict__.copy()


class Student:
    def __init__(self, id_s, fn, ln, dmjr, level, id_r):
        self.ID_S = id_s
        self.FN = fn
        self.LN = ln
        self.DMjr = dmjr
        self.Level = level
        self.ID_R = id_r

    @staticmethod
    def from_json(data, id_s):
        # The server generates the student ID
        if "ID_S" in data or "id" in data:
            raise APIError("Do not send an id, it is generated by the server")

        fn = require_str(data, "FN")
        ln = require_str(data, "LN")

        dmjr = require_int(data, "DMjr")
        if dmjr not in (0, 1):
            raise APIError("Field 'DMjr' must be 0 or 1")

        level = require_int(data, "Level")
        if level not in (1, 2, 3, 4):
            raise APIError("Field 'Level' must be 1, 2, 3 or 4")

        id_r = require_int(data, "ID_R")

        return Student(id_s, fn, ln, dmjr, level, id_r)

    def to_dict(self):
        return self.__dict__.copy()